#!/usr/bin/env node
// Fails when a comment appears somewhere the house rule does not allow one.
//
// The rule is that code explains itself: a place needing an explanatory comment gets restructured
// instead. The one exception is what third parties consume, and that exception is semantic rather
// than syntactic — JSDoc is allowed on a symbol a consumer can see, not on JSDoc-shaped text. Only
// the PACKED type declarations say which symbols those are, which is why this cannot be an ESLint
// rule: ESLint sees one file and cannot know what survives into the tarball.
//
// Three kinds of comment are permitted:
//   1. JSDoc on a declaration that reaches the packed .d.ts, or on a member of one.
//   2. Functional directives — eslint-disable, @ts-*, @internal, prettier-ignore, generated and
//      provenance banners. These instruct a tool; removing them changes behaviour. @internal earns
//      its place the same way @ts-* does: with stripInternal the compiler drops the symbol from the
//      emitted declarations, so the marker is the reason the symbol is not published rather than a
//      comment on something that is not.
//   3. Comments inside template literals, which devkit recipes emit into consumer code. These are
//      not comments at all, they are string contents, and the parser knows the difference. A scan
//      loop does not: at `${` the token ends and it carries on in ordinary code mode, so template
//      text after the closing brace gets tokenised as code and its /* */ looks like a comment. That
//      cost this checker a special case for template spans, and then it cost far more, because the
//      same loop also gives up part-way through such a file and reports nothing about the rest —
//      24 files, 59 comments, silently unread. Comments therefore come from the AST, which reports
//      trivia and never string contents, and the special case is gone with the loop that needed it.
//
// Run it after `nx package plugin-sdk && nx package shell`.

import { readFileSync, readdirSync, existsSync, statSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

const repoRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  '../..',
);

// Directories, not entry points: the packed plugin-sdk index is a barrel of re-exports whose
// declarations sit in sibling files, so reading the entry alone collects nothing. Walking the whole
// packed tree also picks up the members of published types, which is what the rule needs.
//
// EVERY published package that ships declarations belongs here, not just the two the policy names
// in prose. @loomweaver/devkit publishes its recipe option types, so the JSDoc describing what a consumer
// may pass to a generator is consumer-facing IDE documentation exactly like the SDK's. Leaving it
// out made the checker report twelve such blocks as violations. @loomweaver/cli, @loomweaver/mcp and
// @loomweaver/frame-kit ship no declarations at all, so they have nothing to contribute here.
const PACKED = [
  'platform/dist/libs/core/plugin-sdk',
  'platform/dist/libs/core/shell/types',
  'platform/dist/libs/tooling/devkit',
  'platform/dist/libs/integrations/ag-ui',
  // @loomweaver/frame-kit publishes from its source directory rather than through ng-packagr, so its
  // declaration sits beside the bundle it describes. It is a global script, not a module: what a
  // frame surface can name is what it declares at the top level.
  'platform/libs/core/frame-kit/dist',
];

const SCAN_ROOTS = [
  'platform/libs',
  'platform/apps',
  'demo/src',
  'website/src',
];

const SKIP_DIRS = new Set([
  'node_modules',
  'dist',
  'out-tsc',
  '.angular',
  '.nx',
  'coverage',
  'test-results',
  'playwright-report',
  '.astro',
  'generated',
  // Repository tooling, not shipped source. The checkers in here carry a header stating why they
  // exist, which is the one place that rationale can live for a reader who has to decide whether a
  // failing gate is worth keeping.
  'tools',
]);

// Configuration files are outside the rule by standing practice: eslint.config.mjs was deliberately
// left commented when the policy was last swept, because a rule block without its reason is a rule
// nobody dares delete.
const CONFIG_FILE = /\.config\.(mjs|mts|ts|js)$/;

const DIRECTIVE =
  /^\s*(eslint-|@ts-|@internal\b|prettier-ignore|globals\s|jscs|istanbul\s|c8\s|v8\s|@vitest-|#!|GENERATED|Generated by|Provenance:|SPDX-)/;

// A file whose every comment is a provenance or generation banner it did not write itself.
const GENERATED_FILE = /\b(GENERATED|DO NOT EDIT|auto-generated)\b/i;

function walk(dir, out, extensions) {
  for (const entry of readdirSync(dir)) {
    if (SKIP_DIRS.has(entry)) continue;
    const full = path.join(dir, entry);
    if (statSync(full).isDirectory()) walk(full, out, extensions);
    else if (extensions.some((e) => entry.endsWith(e)) && !CONFIG_FILE.test(entry))
      out.push(full);
  }
}

function collect(roots, extensions) {
  const out = [];
  for (const r of roots) {
    const full = path.join(repoRoot, r);
    if (existsSync(full)) walk(full, out, extensions);
  }
  return out.sort();
}

// What a consumer can actually see: every declaration the packed .d.ts carries, and the members of
// those declarations that are not private.
//
// Reachability rather than the export list, because ng-packagr emits exactly what a consumer's
// compiler can resolve — a published interface's base type is not itself exported and documenting
// it is still contract documentation. `BarItemBase` is that case.
//
// Not private members, and that exclusion is the whole difference from the version this replaced.
// A private member is emitted as a bare `private name;` with no type and no signature: nobody can
// call it, so nothing about it is documentation for anybody. The old set was every identifier
// appearing anywhere in a .d.ts, private lines and parameter names included, which let a comment
// ride on any word that happened to occur somewhere in the contract.
function contract() {
  const declarations = [];
  for (const rel of PACKED) {
    const dir = path.join(repoRoot, rel);
    if (!existsSync(dir)) {
      throw new Error(
        `packed declarations missing: ${rel}\n` +
          'Run `nx package plugin-sdk` and `nx package shell` first — this check reads the ' +
          'tarball contract, not the source barrels.',
      );
    }
    walk(dir, declarations, ['.d.ts']);
  }

  const reachable = new Set();
  const members = new Map();
  const named = (node) =>
    node.name && (ts.isIdentifier(node.name) || ts.isStringLiteral(node.name))
      ? node.name.text
      : undefined;

  for (const entry of declarations) {
    const source = ts.createSourceFile(
      entry,
      readFileSync(entry, 'utf8'),
      ts.ScriptTarget.Latest,
      true,
    );
    const visit = (node) => {
      const name = named(node);
      const declares =
        ts.isClassDeclaration(node) ||
        ts.isInterfaceDeclaration(node) ||
        ts.isTypeAliasDeclaration(node) ||
        ts.isFunctionDeclaration(node) ||
        ts.isEnumDeclaration(node) ||
        ts.isVariableDeclaration(node) ||
        ts.isModuleDeclaration(node);
      if (name && declares) {
        reachable.add(name);
        const visible = members.get(name) ?? new Set();
        for (const member of node.members ?? []) {
          const isPrivate = member.modifiers?.some(
            (modifier) => modifier.kind === ts.SyntaxKind.PrivateKeyword,
          );
          const memberName = named(member);
          if (!isPrivate && memberName) visible.add(memberName);
        }
        members.set(name, visible);
      }
      ts.forEachChild(node, visit);
    };
    ts.forEachChild(source, visit);
  }
  return { reachable, members };
}

// The symbol a comment documents: its own name for a declaration, and owner-plus-member for a
// member of a class, an interface or an enum. The version this replaced collected the whole
// neighbourhood — ancestors, own name and every descendant outside a function body — and let the
// comment pass if any of them was published. That is how JSDoc on an internal helper survived a
// move into an unpublished class: the helper mentioned a parameter called `path`, and something
// published has a property of that name.
function documentedSymbols(source, text) {
  const byOffset = new Map();
  const named = (node) =>
    node.name && (ts.isIdentifier(node.name) || ts.isStringLiteral(node.name))
      ? node.name.text
      : undefined;

  const visit = (node, owner) => {
    let own = named(node);
    if (!own && ts.isVariableStatement(node)) {
      const [declaration] = node.declarationList.declarations;
      if (declaration && ts.isIdentifier(declaration.name)) {
        own = declaration.name.text;
      }
    }
    for (const range of [
      ...(ts.getLeadingCommentRanges(text, node.pos) ?? []),
      ...(ts.getTrailingCommentRanges(text, node.end) ?? []),
    ]) {
      if (!byOffset.has(range.pos)) byOffset.set(range.pos, { owner, own });
    }
    const holdsMembers =
      own &&
      (ts.isClassDeclaration(node) ||
        ts.isInterfaceDeclaration(node) ||
        ts.isEnumDeclaration(node) ||
        ts.isTypeAliasDeclaration(node));
    ts.forEachChild(node, (child) => visit(child, holdsMembers ? own : owner));
  };
  ts.forEachChild(source, (child) => visit(child, undefined));
  return byOffset;
}

// Comments come from the AST, not from a raw scan loop. A scan loop terminates early on a file
// whose template literals carry a substitution — at `${` the token ends and the loop carries on in
// ordinary code mode until something makes it give up, and everything after that point is simply
// never seen. Twenty-four files in this repository ended that way, hiding 55 JSDoc blocks from the
// guard that exists to find them. Walking every node's leading and trailing trivia sees all of them.
function commentsOf(source, text) {
  const found = new Map();
  const take = (ranges) => {
    for (const range of ranges ?? []) {
      if (found.has(range.pos)) continue;
      const raw = text.slice(range.pos, range.end);
      found.set(range.pos, {
        pos: range.pos,
        text: raw,
        jsdoc:
          range.kind === ts.SyntaxKind.MultiLineCommentTrivia &&
          raw.startsWith('/**'),
      });
    }
  };
  const visit = (node) => {
    take(ts.getLeadingCommentRanges(text, node.pos));
    take(ts.getTrailingCommentRanges(text, node.end));
    ts.forEachChild(node, visit);
  };
  visit(source);
  return [...found.values()].sort((a, b) => a.pos - b.pos);
}

function lineOf(text, pos) {
  return text.slice(0, pos).split('\n').length;
}

function withoutTrailingStars(text) {
  let end = text.length;
  while (end > 0 && text[end - 1] === '*') {
    end -= 1;
  }
  return text.slice(0, end);
}

function body(comment) {
  const opened = comment.text.replace(/^\/\*+/, '');
  return (opened.endsWith('*/') ? withoutTrailingStars(opened.slice(0, -2)) : opened)
    .replace(/^\/\//, '')
    .split('\n')
    .map((l) => l.replace(/^\s*\*?\s?/, ''))
    .join(' ')
    .trim();
}

const { reachable, members } = contract();
const violations = [];

for (const file of collect(SCAN_ROOTS, ['.ts', '.mts', '.mjs'])) {
  const text = readFileSync(file, 'utf8');
  if (GENERATED_FILE.test(text.slice(0, 400))) continue;

  const source = ts.createSourceFile(
    file,
    text,
    ts.ScriptTarget.Latest,
    true,
    file.endsWith('.mjs') ? ts.ScriptKind.JS : ts.ScriptKind.TS,
  );
  const documented = documentedSymbols(source, text);
  for (const comment of commentsOf(source, text)) {
    const content = body(comment);
    if (DIRECTIVE.test(content) || DIRECTIVE.test(comment.text)) continue;
    if (comment.jsdoc) {
      const { owner, own } = documented.get(comment.pos) ?? {};
      const visible = owner
        ? reachable.has(owner) && (members.get(owner)?.has(own) ?? false)
        : own !== undefined && reachable.has(own);
      if (visible) continue;
    }
    violations.push({
      file: path.relative(repoRoot, file),
      line: lineOf(text, comment.pos),
      pos: comment.pos,
      end: comment.pos + comment.text.length,
      kind: comment.jsdoc ? 'jsdoc on an unpublished symbol' : 'comment',
      excerpt: content.slice(0, 72),
    });
  }
}

for (const file of collect(SCAN_ROOTS, ['.html'])) {
  const text = readFileSync(file, 'utf8');
  for (const match of text.matchAll(/<!--([\s\S]*?)-->/g)) {
    const content = match[1].trim();
    if (DIRECTIVE.test(content)) continue;
    violations.push({
      file: path.relative(repoRoot, file),
      line: lineOf(text, match.index),
      kind: 'template comment',
      excerpt: content.slice(0, 72),
    });
  }
}

if (process.argv[2] === '--json') {
  console.log(JSON.stringify(violations));
  process.exit(0);
}

const scope = process.argv[2];
const reported = scope
  ? violations.filter((v) => v.file.startsWith(scope))
  : violations;

// Scoped runs are the calibration path: they answer "is the checker right about a corpus whose
// answer we already know", so they ignore the residue entirely.
if (scope) {
  if (reported.length > 0) {
    for (const v of reported) {
      console.error(`${v.file}:${v.line}  ${v.kind}: ${v.excerpt}`);
    }
    console.error(
      `\ncheck-comments: ${reported.length} disallowed comment(s) under ${scope}`,
    );
    process.exit(1);
  }
  console.log(
    `check-comments: no disallowed comments under ${scope} ` +
      `(${reachable.size} reachable declarations read from the packed declarations)`,
  );
  process.exit(0);
}

const residuePath = path.join(repoRoot, 'platform/tools/comment-residue.json');
const residue = existsSync(residuePath)
  ? JSON.parse(readFileSync(residuePath, 'utf8')).files
  : {};

const counts = {};
for (const v of reported) counts[v.file] = (counts[v.file] ?? 0) + 1;

const failures = [];
for (const [file, count] of Object.entries(counts).sort()) {
  const allowed = residue[file] ?? 0;
  if (count > allowed) {
    for (const v of reported.filter((v) => v.file === file).slice(allowed)) {
      console.error(`${v.file}:${v.line}  ${v.kind}: ${v.excerpt}`);
    }
    failures.push(`${file}: ${count} comments, residue allows ${allowed}`);
  }
}
for (const [file, allowed] of Object.entries(residue).sort()) {
  const count = counts[file] ?? 0;
  if (count < allowed) {
    failures.push(
      `${file}: down to ${count} from ${allowed} — trim the residue to ${count}` +
        (count === 0 ? ' (remove the entry)' : ''),
    );
  }
}

if (failures.length > 0) {
  console.error('\ncheck-comments:');
  for (const f of failures) console.error(`  ${f}`);
  console.error(
    '\nThe residue is a ratchet: it may shrink and may never grow. A new comment needs the ' +
      'code restructured instead, or the symbol published.',
  );
  process.exit(1);
}

const total = Object.values(residue).reduce((a, b) => a + b, 0);
console.log(
  `check-comments: clean against the residue (${total} known comments in ` +
    `${Object.keys(residue).length} files, ${reachable.size} reachable declarations read from the ` +
    'packed declarations)',
);
